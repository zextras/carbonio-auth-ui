import { fetchSoap } from '../fetchSoap';
import {
	mobileQrMobileResponseRequest,
	mobileQrTokenCheckRequest,
	mobileQrValidateNumberRequest
} from '../mobile-qr-credential';

vi.mock('../fetchSoap', () => ({
	fetchSoap: vi.fn()
}));

const USER = 'user@example.com';
const NAMESPACE = 'urn:zextrasClient';

describe('mobile QR credential requests', () => {
	beforeEach(() => {
		vi.mocked(fetchSoap).mockResolvedValue({});
	});

	it('should check whether a mobile QR token exists', async () => {
		await mobileQrTokenCheckRequest('qr-token', USER);

		expect(fetchSoap).toHaveBeenCalledWith('MobileQRCredentialUITokenCheckRequest', {
			_jsns: NAMESPACE,
			token: 'qr-token',
			user: USER
		});
	});

	it('should request the mobile response details', async () => {
		await mobileQrMobileResponseRequest('My phone', USER);

		expect(fetchSoap).toHaveBeenCalledWith('MobileQRCredentialUIMobileResponseRequest', {
			_jsns: NAMESPACE,
			label: 'My phone',
			user: USER
		});
	});

	it('should validate the number generated by the mobile device', async () => {
		await mobileQrValidateNumberRequest('My phone', USER, 123456);

		expect(fetchSoap).toHaveBeenCalledWith('MobileQRCredentialUIValidateNumberRequest', {
			_jsns: NAMESPACE,
			label: 'My phone',
			user: USER,
			mobileGeneratedNumber: 123456
		});
	});
});
